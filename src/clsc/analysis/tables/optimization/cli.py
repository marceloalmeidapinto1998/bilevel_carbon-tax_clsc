"""Command-line interface for the aggregate optimization-result table."""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

from .core import load_rows, write_all_methods_outputs


def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="python -m clsc.analysis.tables.optimization",
        description="Create the aggregate policy-result LaTeX and PDF table "
                    "from results/runs/base/*/*/summary.json.",
    )
    p.add_argument("--results-base", type=Path, default=Path("results/runs/base"),
                   help="Directory containing instance result folders.")
    p.add_argument("--analysis-root", type=Path, default=Path("results/runs/base"),
                   help="Root result directory. The summary table is written "
                        "under its summary subfolder.")
    p.add_argument("--no-pdf", action="store_true",
                   help="Write only .tex files and skip pdflatex compilation.")
    p.add_argument("--keep-latex-build-files", action="store_true",
                   help="Keep auxiliary LaTeX files generated by pdflatex.")
    return p


def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    if not args.results_base.exists():
        raise SystemExit(f"Results directory does not exist: {args.results_base}")

    compile_pdf = not args.no_pdf
    if compile_pdf and shutil.which("pdflatex") is None:
        print("pdflatex was not found; writing .tex files only.")
        compile_pdf = False

    rows = load_rows(args.results_base)
    if not rows:
        raise SystemExit(f"No summary.json files found under {args.results_base}")

    _, pdf_path = write_all_methods_outputs(
        rows,
        args.analysis_root,
        compile_pdf=compile_pdf,
        keep_latex_build_files=args.keep_latex_build_files,
    )

    print(f"Wrote aggregate LaTeX table under {args.analysis_root / 'summary'}")
    if compile_pdf:
        status = "and PDF" if pdf_path is not None else "but PDF compilation did not produce a file"
        print(f"Wrote aggregate table {status}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
